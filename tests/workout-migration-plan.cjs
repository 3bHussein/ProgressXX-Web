const assert=require('node:assert/strict');
const {planWorkoutMigration}=require('../scripts/plan-workout-migration.cjs');
const workout=(id,exercise='Squat')=>({id,day:'Monday',week:4,date:'2026-10-01',time:'08:00',exercise,performance:'80kg x 8',status:'Completed',notes:'Original notes'});
const input={'progressx-data-v19':JSON.stringify([workout('a'),workout('a'),workout('b'),workout('c'),workout('d'),{id:'noexercise'}]),'progressx-workout-deleted-ids-v1':JSON.stringify(['b'])};
const original=JSON.stringify(input);
const plan=planWorkoutMigration(input,['pxlog:c'],1);
assert.equal(plan.stats.total,6);
assert.equal(plan.stats.eligible,2);
assert.equal(plan.stats.deleted,1);
assert.equal(plan.stats.alreadySynced,1);
assert.equal(plan.stats.duplicates,1);
assert.equal(plan.stats.invalid,1);
assert.equal(plan.batches.length,2);
assert.deepEqual(plan.batches.map(batch=>batch[0].source_id),['pxlog:a','pxlog:d']);
assert.equal(plan.batches[0][0].raw_performance,'80kg x 8');
assert.equal(plan.batches[0][0].notes,'Original notes');
assert.equal(JSON.stringify(input),original,'Planner must not modify original snapshot');
assert.deepEqual(planWorkoutMigration(input,['pxlog:a','pxlog:c','pxlog:d'],100).stats.eligible,0);
assert.throws(()=>planWorkoutMigration({'progressx-data-v19':'{not json'}),/Malformed/);
assert.throws(()=>planWorkoutMigration(input,[],0),/Invalid batch size/);
console.log('PASS: dry-run migration counts, preserves history, excludes tombstones, avoids duplicates and is repeatable');
