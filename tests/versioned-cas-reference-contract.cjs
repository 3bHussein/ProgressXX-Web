const assert=require('node:assert/strict');
const {createVersionedStore}=require('../scripts/versioned-cas-reference.cjs');
const store=createVersionedStore({A:{daily:{x:'water'},workout:{day:'rest'}}});
const a=store.read('A'),b=store.read('A');
const deleted=structuredClone(a.payload);delete deleted.daily.x;
