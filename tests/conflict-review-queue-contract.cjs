'use strict';
const assert=require('node:assert/strict');
const {createReviewQueue}=require('../scripts/conflict-review-queue.cjs');
const db=new Map(),storage={getItem:k=>db.has(k)?db.get(k):null,setItem:(k,v)=>db.set(k,v),removeItem:k=>db.delete(k)};
const A=createReviewQueue({accountId:'A',storage}),B=createReviewQueue({accountId:'B',storage});
const draft={daily:{water:{text:'local'}}},remote={daily:{}};
assert.equal(A.load(),null);A.capture({draft,remote,revision:12});
draft.daily.water.text='changed';assert.equal(A.load().draft.daily.water.text,'local');
assert.equal(B.load(),null);assert.notEqual(A.key,B.key);
assert.throws(()=>A.capture({draft,remote,revision:13}),/already exists/);
const reload=createReviewQueue({accountId:'A',storage});
assert.equal(reload.load().revision,12);assert.equal(reload.load().status,'awaiting-review');
assert.throws(()=>reload.clearAfterAcknowledgement(false),/approval/);
assert.equal(reload.load().draft.daily.water.text,'local');
assert.equal(reload.clearAfterAcknowledgement(true),true);
assert.equal(reload.load(),null);assert.equal(B.load(),null);
const blocked={getItem:k=>null,setItem(){throw Error('storage quota')}};
assert.throws(()=>createReviewQueue({accountId:'C',storage:blocked}).capture({draft,remote}),/storage quota/);
assert.throws(()=>createReviewQueue({accountId:'',storage}),/Account ID/);
for(const id of [undefined,null,42,{},'   '])assert.throws(()=>createReviewQueue({accountId:id,storage}),/Account ID required/);
const spaced=createReviewQueue({accountId:' A ',storage});
assert.equal(spaced.key,A.key);
spaced.capture({draft:{daily:{a:1}},remote:{},revision:3});
assert.deepEqual(A.load().draft,{daily:{a:1}});
assert.equal(spaced.load().accountId,'A');
assert.equal(A.clearAfterAcknowledgement(true),true);
console.log('PASS: isolated account-scoped conflict drafts survive reload, resist overwrite, require explicit ack, and surface storage failures');
console.log('NOT PRODUCTION: no conflict queue is loaded by index.html or wired to Supabase.');
